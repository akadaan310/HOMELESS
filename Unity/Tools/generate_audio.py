#!/usr/bin/env python3
"""Original deterministic test signals. Not recorded ambience, speech or production audio."""
import hashlib,json,math,pathlib,random,struct,wave
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=ROOT/'Assets/Resources/Audio'
RATE=24000

def write(name, values):
    pcm=b''.join(struct.pack('<h',max(-32768,min(32767,round(v*32767)))) for v in values)
    path=OUT/(name+'.wav')
    with wave.open(str(path),'wb') as w:
        w.setnchannels(1);w.setsampwidth(2);w.setframerate(RATE);w.writeframes(pcm)
    return {'id':name,'path':str(path.relative_to(ROOT)),'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'frames':len(values),'sample_rate':RATE,'channels':1,'peak':max(map(abs,values)),'rms':math.sqrt(sum(x*x for x in values)/len(values)),'stage':'integrity_checked','provenance':'original deterministic synthetic signal generated by Tools/generate_audio.py','native_playback':'NOT_RUN','rights':'original generated test signal; no third-party recordings or voices'}

def main():
    OUT.mkdir(parents=True,exist_ok=True)
    n=RATE*6
    engine=[.16*math.sin(2*math.pi*48*i/RATE)+.06*math.sin(2*math.pi*96*i/RATE)+.03*math.sin(2*math.pi*144*i/RATE) for i in range(n)]
    rng=random.Random(20261021);low=0;cafe=[]
    for i in range(n):
        low=.985*low+.015*rng.uniform(-1,1)
        envelope=min(1,i/(RATE*.08),(n-1-i)/(RATE*.08))
        cafe.append(.45*low*envelope)
    step=[]
    for i in range(int(RATE*.18)):
        t=i/RATE;envelope=math.sin(math.pi*i/(RATE*.18))**2*math.exp(-18*t)
        step.append(.3*envelope*(.7*rng.uniform(-1,1)+.3*math.sin(2*math.pi*130*t)))
    manifest={'schema':1,'policy_digest':'e9327cbf55e496f3ad5029e409d6201f68d6095753a5ad95c58328cb6e8a4104','label':'development test signals, not release sound library','assets':[write('engine',engine),write('cafe',cafe),write('step',step)]}
    (ROOT/'Evidence/audio-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')

if __name__=='__main__':main()
